// ===== Quiz Logic =====
let gameData = [];
let currentIndex = 0;
let selectedAnswer = '';
let score = 0;

function startQuizList() {
  gameData = lessons[0].questions;
  currentIndex = 0;
  score = 0;
  document.getElementById('question-section').style.display = 'block';
  loadQuestion();
}

let selectedWords = [];

function loadQuestion(qData) {
  if (!qData) return;

  // Hindi text
  document.getElementById('hindi-text').innerText = qData.hindi || qData.hind || "";
  
  // English question upar Hindi ke niche dikhane ke liye
  document.getElementById('english-ref').innerText = qData.english || qData.q || "";
  
  // Options shuffle karo
  let words = qData.words || qData.options || [];
  words = words.sort(() => Math.random() - 0.5);
  
  // Word bank banao
  const wordBank = document.getElementById('word-bank');
  wordBank.innerHTML = words
   .map(w => `<button class="word-btn" onclick="addWord('${w}', this)">${w}</button>`)
   .join('');
  
  // Answer box empty
  document.getElementById('answer-box').innerHTML = '';
  selectedWords = [];
  
  // Reset
  document.getElementById('feedback').style.display = 'none';
  document.getElementById('check-btn').style.display = 'inline-block';
  document.getElementById('next-btn').style.display = 'none';
}

function addWord(word, btn) {
  selectedWords.push(word);
  updateAnswerBox();
  
  // Button ko hide karo word-bank se
  btn.style.display = 'none';
}

function removeWord(word, index, btn) {
  selectedWords.splice(index, 1);
  updateAnswerBox();
  
  // Wapas word-bank me show karo
  const wordBankBtns = document.querySelectorAll('#word-bank button');
  wordBankBtns.forEach(b => {
    if (b.innerText === word && b.style.display === 'none') {
      b.style.display = 'inline-block';
    }
  });
}

function updateAnswerBox() {
  const answerBox = document.getElementById('answer-box');
  answerBox.innerHTML = selectedWords
    .map((w, i) => `<button class="word-btn" onclick="removeWord('${w}', ${i}, this)">${w}</button>`)
    .join(' ');
}
function renderOptions(question) {
  const optionsDiv = document.getElementById('options');
  const answerInput = document.getElementById('answer-input');
  optionsDiv.innerHTML = '';
  selectedAnswer = '';
  if (question.options && question.options.length > 0) {
    if(answerInput) answerInput.style.display = 'none';
    question.options.forEach(opt => {
      let btn = document.createElement('button');
      btn.innerText = opt;
      btn.className = 'option';
      btn.style.cssText = 'width:100%;padding:12px;margin:6px 0;border:2px solid #4CAF50;border-radius:8px;background:#fff;font-size:16px;cursor:pointer';
      btn.onclick = function() {
        document.querySelectorAll('.option').forEach(b => {
          b.style.background = '#fff';
          b.style.color = '#000';
        });
        btn.style.background = '#4CAF50';
        btn.style.color = '#fff';
        selectedAnswer = opt;
      };
      optionsDiv.appendChild(btn);
    });
  } else {
    if(answerInput) answerInput.style.display = 'block';
  }
}

function checkAnswer() {
  if (!selectedAnswer) {
    alert('Pehle option select karo');
    return;
  }
  let correct = gameData[currentIndex].answer;
  if (selectedAnswer.trim().toLowerCase() === correct.trim().toLowerCase()) {
    score++;
    document.getElementById('result').innerText = 'Sahi! ✅';
    document.getElementById('result').style.color = 'green';
  } else {
    document.getElementById('result').innerText = `Galat! Sahi answer: ${correct}`;
    document.getElementById('result').style.color = 'red';
  }
  setTimeout(() => {
    currentIndex++;
    loadQuestion();
  }, 1500);
}
